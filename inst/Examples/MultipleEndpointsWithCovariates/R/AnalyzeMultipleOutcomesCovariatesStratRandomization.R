######################################################################################################################## .
#' @name AnalyzeMultipleOutcomesCovariatesStratRandomization
#' @title Analyze Simulated Patient Data with Multiple Independent Outcomes and Stratified Randomization
#' @description This function performs statistical analysis on simulated patient-level data with multiple
#'   continuous endpoints, binary covariates and stratified randomization. For each endpoint, it fits an ANCOVA
#'   model to assess the treatment effect while adjusting for covariates. The function returns binary decisions for
#'   treatment and covariate effects, along with group-wise means and sample sizes. The output of this function is
#'   generated dynamically based on the number of covariates and endpoints, but it follows the same logic as the
#'   explicitly constructed output list in `AnalyzeMultipleOutcomes.R`.
#' @author Julija Saltane
#' @param SimData Data frame of subject-level data for the current simulation, with one row per subject. Access
#'   columns by name, for example `SimData$TreatmentID`. Columns include the fields below when applicable,
#'   plus any custom outputs from enrollment, randomization, response, or dropout generation.
#' \describe{
#'   \item{TreatmentID}{Integer vector of treatment assignments, with one element per subject: 0 = placebo/control,
#'     1 = first experimental arm, 2 = second experimental arm, and so on.}
#'   \item{Response}{Numeric vector of generated subject responses, with one element per subject.}
#' }
#'
#' Additional fields returned by SimulateMultipleOutcomesCovariatesStratRandomization:
#' \describe{
#'   \item{PatientOutcome1}{Numeric vector of simulated values for continuous outcome 1, with one element per subject.}
#'   \item{PatientOutcome2}{Numeric vector of simulated values for continuous outcome 2, with one element per subject.}
#'   \item{PatientOutcome3}{Numeric vector of simulated values for continuous outcome 3, with one element per subject.}
#'   \item{Covariate1}{Binary vector of simulated values for covariate 1}
#'   \item{Covariate2}{Binary vector of simulated values for covariate 2}
#'   \item{PatientTreatmentID}{Integer vector of treatment assignments generated by stratified randomization,
#'     with one element per subject: 0 = control; 1 = treatment.}
#' }
#' @param DesignParam Named list of design and simulation parameters. Access elements by name, for example
#'   `DesignParam$Alpha`, rather than by position. Availability depends on the endpoint, design, and East Horizon product
#'   as indicated below. The fields listed here are used by this example.
#' \describe{
#'   \item{Alpha}{Numeric type I error rate (significance level).}
#' }
#' @param LookInfo Optional look information; not used by this example.
#' @param UserParam Optional named list of user-defined parameters supplied through East Horizon. The default is
#'   NULL. Access elements by name, for example `UserParam$ParameterName`, rather than by position. User-defined
#'   scalar parameters may be integer, numeric, or character values. Pass the individual named elements to helper
#'   functions so East Horizon can identify and populate the required parameters.
#' @return Named list containing the outputs returned by this example.
#' \describe{
#'   \item{Decision}{Integer boundary-crossing code: 0 = no boundary crossed; 1 = lower efficacy boundary crossed;
#'     2 = upper efficacy boundary crossed; 3 = futility boundary crossed; 4 = equivalence boundary crossed
#'     (unavailable in East Horizon Explore).}
#'   \item{ErrorCode}{Optional integer execution status: 0 = no error; a positive value aborts the current
#'     simulation but allows subsequent simulations to run; a negative value is fatal and stops all further
#'     simulations.}
#' }
#'
#' Example-specific additional output elements:
#' \describe{
#'   \item{SampleSizeCtrl}{Number of patients in the control group}
#'   \item{SampleSizeTrt}{Number of patients in the treatment group}
#'   \item{MeanOutcome[X]Ctrl}{Mean outcome for the control group for endpoint X, where X = 1, 2, 3.}
#'   \item{MeanOutcome[X]Trt}{Mean outcome for the treatment group for endpoint X, where X = 1, 2, 3.}
#'   \item{DecisionOutcome[X]Trt}{Binary decisions (1 = significant, 0 = not significant) for treatment effect for
#'     endpoint X}
#'   \item{DecisionOutcome[X]Covariate[Y]}{Binary decisions (1 = significant, 0 = not significant) for endpoint X
#'     for covariate Y}
#'   \item{PValueOutcome[X]Trt}{p-value for endpoint X for treatment}
#'   \item{PValueOutcome[X]Covariate[Y]}{p-value for endpoint X for covariate Y}
#' }
#'
#' Example-specific output usage: Decision: Placeholder value (always 1)
######################################################################################################################## .

AnalyzeMultipleOutcomesCovariatesStratRandomization <- function( SimData, DesignParam, LookInfo = NULL, UserParam = NULL ) {

    # Extract 1-sided Type I error and transform it into two-sided for ANCOVA
    dAlphaOneSided <- DesignParam$Alpha
    dAlphaTwoSided <- dAlphaOneSided * 2

    # Extract outcomes and covariates
    lPatientOutcomes <- as.list( SimData[ , grep( "PatientOutcome", names( SimData ) ) ] )
    lCovariates <- as.list( SimData[ , grep( "Covariate", names( SimData ) ) ] )

    # Determine number of endpoints and covariates
    nQtyOfEndpoints <- length( lPatientOutcomes )
    nQtyOfCovariates <- length( lCovariates )

    # Create a vector of treatment assignments generated through stratified randomization
    vTreatmentID <- SimData$PatientTreatmentID

    # Determine the number of patients in each group
    nSampleSizeCtrl <- sum( vTreatmentID == 0 )
    nSampleSizeTrt <- sum( vTreatmentID == 1 )

    # Initialize lists and vectors to store results for each endpoint
    lPValues <- vector( "list", nQtyOfEndpoints )
    lDecision <- vector( "list", nQtyOfEndpoints )

    vMeanOutcomeCtrl <- numeric( nQtyOfEndpoints )
    vMeanOutcomeTrt <- numeric( nQtyOfEndpoints )

    # Run separate ANCOVA for each endpoint
    for ( i in 1:nQtyOfEndpoints ) {
        # Compute group means
        vMeanOutcomeCtrl[ i ] <- mean( lPatientOutcomes[[ i ]][ vTreatmentID == 0 ] )
        vMeanOutcomeTrt[ i ] <- mean( lPatientOutcomes[[ i ]][ vTreatmentID == 1 ] )

        # Build formula dynamically: outcome ~ TreatmentID + Covariate 1 + Covariate 2
        strPartOfFormula <- paste( c( "vTreatmentID", paste0( "lCovariates[[ ", seq_len( nQtyOfCovariates ), " ]]" ) ),
            collapse = " + "
        )
        strFormula <- stats::as.formula( paste( "lPatientOutcomes[[ i ]] ~", strPartOfFormula ) )

        # Perform ANCOVA
        dfAnalysisResult <- broom::tidy( stats::aov( strFormula ) )

        # Extract the p values. Note that the last value is for residuals
        lPValues[[ i ]] <- utils::head( dfAnalysisResult$p.value, -1 )
        lDecision[[ i ]] <- as.integer( lPValues[[ i ]] <= dAlphaTwoSided )
    }

    # Return the analysis results, sample sizes of each group and means of outcomes
    lReturn <- list(
        Decision = as.integer( 1 ),
        ErrorCode = as.integer( 0 ),
        SampleSizeCtrl = as.integer( nSampleSizeCtrl ),
        SampleSizeTrt = as.integer( nSampleSizeTrt )
    )

    # Add mean outcome and treatment decision
    for ( i in 1:nQtyOfEndpoints ) {
        lReturn[[ paste0( "MeanOutcome", i, "Ctrl" ) ]] <- as.double( vMeanOutcomeCtrl[ i ] )
        lReturn[[ paste0( "MeanOutcome", i, "Trt" ) ]] <- as.double( vMeanOutcomeTrt[ i ] )
        lReturn[[ paste0( "PValueOutcome", i, "Trt" ) ]] <- as.double( lPValues[[ i ]][ 1 ] )
        lReturn[[ paste0( "DecisionOutcome", i, "Trt" ) ]] <- as.integer( lDecision[[ i ]][ 1 ] )
    }

    # Add p-values and covariate decisions
    for ( j in 1:nQtyOfCovariates ) {
        for ( i in 1:nQtyOfEndpoints ) {
            lReturn[[ paste0( "PValueOutcome", i, "Covariate", j ) ]] <- as.double( lPValues[[ i ]][ j + 1 ] )
            lReturn[[ paste0( "DecisionOutcome", i, "Covariate", j ) ]] <- as.integer( lDecision[[ i ]][ j + 1 ] )
        }
    }

    return( lReturn )
}
